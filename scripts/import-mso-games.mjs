/**
 * Turns a scraped MyStatsOnline schedule into the league's games.
 *
 *   node scripts/import-mso-games.mjs <slug> <schedule.json> <team-mode.json> [out.sql]
 *
 * Runs after import-mso-league.mjs, which creates the seasons and the clubs
 * these games point at, and before import-boxscores.mjs, which hangs line
 * scores and box scores off the source ids written here.
 *
 * Only this league's games are touched. The schedule names a club by its
 * nickname alone - "Sandals", never "ALF Sandals (MIBL)" - so the clubs are
 * matched back through the season's own team list rather than by name.
 */
import fs from "node:fs";

const [slug, schedulePath, teamModePath] = process.argv.slice(2);
const outputPath = process.argv[5] ?? `drizzle/seed-${slug}-games.sql`;

if (!slug || !schedulePath || !teamModePath) {
  console.error("usage: node scripts/import-mso-games.mjs <slug> <schedule.json> <team-mode.json> [out.sql]");
  process.exit(1);
}

const schedule = JSON.parse(fs.readFileSync(schedulePath, "utf8"));
const teamMode = JSON.parse(fs.readFileSync(teamModePath, "utf8"));

const sqlStr = (value) =>
  value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`;
const sqlNum = (value) => (value === null || value === undefined ? "NULL" : String(value));

const score = (value) => {
  const text = String(value ?? "").trim();
  if (!text || text === "-" || text === "--") return null;
  const parsed = Number.parseInt(text, 10);
  return Number.isFinite(parsed) ? parsed : null;
};

/** "ALF Sandals (MIBL)" -> "sandals", which is what a schedule calls them. */
const nickname = (sourceName) =>
  String(sourceName ?? "")
    .replace(/^[A-Z]{2,4}\s+/, "")
    .replace(/\s*\(MIBL\)\s*$/i, "")
    .trim()
    .toLowerCase();

// Which club is which, per season, from the same scrape the clubs came from.
const teamsBySeason = new Map();
for (const record of teamMode.seasons) {
  const bySeason = teamsBySeason.get(record.seasonId) ?? new Map();
  const key = nickname(record.teamName);
  if (bySeason.has(key)) {
    console.error(`! ${record.seasonName}: two clubs both called "${key}" - games cannot be told apart`);
  }
  bySeason.set(key, record.teamId);
  teamsBySeason.set(record.seasonId, bySeason);
}

const lines = [
  `-- Generated by scripts/import-mso-games.mjs for ${slug} - do not edit by hand.`,
  "-- Only this league's games are touched.",
  "",
];

const seasonRef = (sourceSeasonId) =>
  `(SELECT id FROM historical_seasons WHERE source_season_id = ${sqlStr(String(sourceSeasonId))} ` +
  `AND league_id = (SELECT id FROM leagues WHERE slug = ${sqlStr(slug)}))`;

const sourceIds = schedule.seasons.map((season) => String(season.seasonId));
const scope = sourceIds.map((id) => sqlStr(id)).join(", ");
lines.push(
  `DELETE FROM historical_game_stats WHERE game_id IN (SELECT id FROM historical_games WHERE season_id IN ` +
    `(SELECT id FROM historical_seasons WHERE source_season_id IN (${scope}) AND league_id = (SELECT id FROM leagues WHERE slug = ${sqlStr(slug)})));`,
  `DELETE FROM historical_line_scores WHERE game_id IN (SELECT id FROM historical_games WHERE season_id IN ` +
    `(SELECT id FROM historical_seasons WHERE source_season_id IN (${scope}) AND league_id = (SELECT id FROM leagues WHERE slug = ${sqlStr(slug)})));`,
  `DELETE FROM historical_games WHERE season_id IN (SELECT id FROM historical_seasons WHERE source_season_id IN (${scope}) ` +
    `AND league_id = (SELECT id FROM leagues WHERE slug = ${sqlStr(slug)}));`,
  "",
);

let games = 0;
let unplayed = 0;
const unmatched = new Set();

for (const season of schedule.seasons) {
  const teams = teamsBySeason.get(season.seasonId) ?? new Map();
  const ref = seasonRef(season.seasonId);
  lines.push(`-- ${season.seasonName ?? season.seasonId}`);

  for (const [index, game] of (season.games ?? []).entries()) {
    const awayId = teams.get(String(game.away ?? "").trim().toLowerCase());
    const homeId = teams.get(String(game.home ?? "").trim().toLowerCase());
    if (!awayId || !homeId) {
      if (!awayId) unmatched.add(`${season.seasonName}: ${game.away}`);
      if (!homeId) unmatched.add(`${season.seasonName}: ${game.home}`);
      continue;
    }
    const teamRef = (sourceTeamId) =>
      `(SELECT id FROM historical_teams WHERE season_id = ${ref} AND source_team_id = ${sqlStr(String(sourceTeamId))})`;
    const away = score(game.awayScore);
    const home = score(game.homeScore);
    if (away === null || home === null) unplayed += 1;
    lines.push(
      `INSERT INTO historical_games (source_game_id, season_id, played_on, away_team_id, home_team_id, away_score, home_score, sort_order) ` +
        `VALUES (${sqlStr(String(game.gameId))}, ${ref}, ${sqlStr(game.date || null)}, ${teamRef(awayId)}, ${teamRef(homeId)}, ` +
        `${sqlNum(away)}, ${sqlNum(home)}, ${index});`,
    );
    games += 1;
  }
  lines.push("");
}

fs.writeFileSync(outputPath, lines.join("\n") + "\n");
console.log(`Wrote ${outputPath}`);
console.log(`  games: ${games} (${unplayed} without a score)`);
if (unmatched.size > 0) {
  console.log(`  clubs a game named but the season's team list does not have:`);
  for (const name of unmatched) console.log(`    ${name}`);
}
