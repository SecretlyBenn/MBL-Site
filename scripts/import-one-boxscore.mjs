/**
 * Imports the box score for ONE game, leaving the rest of the archive alone.
 *
 *   node scripts/import-one-boxscore.mjs <boxscores.json> <sourceGameId> [out.sql]
 *
 * import-boxscores.mjs rebuilds the whole archive: it opens with
 * `DELETE FROM historical_game_stats;` and repopulates from a full scrape.
 * That is right for a re-import and catastrophic for a single correction, so
 * this exists for the one-game case - it deletes only the rows belonging to the
 * game named on the command line.
 *
 * Per-inning cells are written only when they add up to the run total. Before
 * Season XI the league recorded final runs and left the innings blank, which
 * arrives here as a row of zeros beside a non-zero R; storing that would draw a
 * line score contradicting its own final score.
 */
import fs from "node:fs";

const [, , boxPath, sourceGameId, outArg] = process.argv;
if (!boxPath || !sourceGameId) {
  console.error("usage: node scripts/import-one-boxscore.mjs <boxscores.json> <sourceGameId> [out.sql]");
  process.exit(1);
}
const outputPath = outArg ?? `import-${sourceGameId}.sql`;

const num = (value) => {
  if (value === undefined || value === null) return null;
  const text = String(value).trim();
  if (!text || text === "-" || text === "--") return null;
  const parsed = Number.parseFloat(text);
  return Number.isFinite(parsed) ? parsed : null;
};
const int = (value) => {
  const parsed = num(value);
  return parsed === null ? null : Math.round(parsed);
};
/** Innings pitched use baseball notation: .1 and .2 mean thirds. */
const innings = (value) => {
  const raw = num(value);
  if (raw === null) return null;
  const whole = Math.trunc(raw);
  const outs = Math.round((raw - whole) * 10);
  return outs === 1 ? whole + 1 / 3 : outs === 2 ? whole + 2 / 3 : whole;
};
const sqlStr = (value) =>
  value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`;
const sqlNum = (value) => (value === null || value === undefined ? "NULL" : String(value));
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

const BAT = {
  AB: "atBats", R: "runs", H: "hits", "2B": "doubles", "3B": "triples",
  HR: "homeRuns", RBI: "rbis", BB: "walks", SO: "strikeouts",
};
const PIT = {
  IP: "inningsPitched", ER: "earnedRuns", H: "hitsAllowed", R: "runsAllowed",
  SO: "strikeoutsPitched", BB: "walksAllowed",
};
const COLUMNS = [
  "atBats", "runs", "hits", "doubles", "triples", "homeRuns", "rbis", "walks",
  "strikeouts", "inningsPitched", "earnedRuns", "hitsAllowed", "runsAllowed",
  "strikeoutsPitched", "walksAllowed",
];

const box = JSON.parse(fs.readFileSync(boxPath, "utf8"));
const game = (box.games ?? []).find((row) => String(row.gameId) === String(sourceGameId));
if (!game) {
  console.error(`No box score for game ${sourceGameId} in ${boxPath}.`);
  process.exit(1);
}

const where = `(SELECT id FROM historical_games WHERE source_game_id = ${sqlStr(sourceGameId)})`;
const lines = [
  `-- Box score for game ${sourceGameId}, generated by scripts/import-one-boxscore.mjs.`,
  `-- Scoped to this game only: nothing else in the archive is touched.`,
  `DELETE FROM historical_line_scores WHERE game_id = ${where};`,
  `DELETE FROM historical_game_stats WHERE game_id = ${where};`,
];

// Line score. The header ends with R, H, E; everything between the team name
// and the first blank column is a half-inning.
const header = game.line[0] ?? [];
const rIndex = header.lastIndexOf("R");
const hIndex = header.lastIndexOf("H");
const eIndex = header.lastIndexOf("E");
const inningEnd = header.findIndex((cell, index) => index > 0 && cell === "");

let sides = 0;
game.line.slice(1).forEach((row, index) => {
  const runs = int(row[rIndex]);
  const perInning = row
    .slice(1, inningEnd === -1 ? rIndex : inningEnd)
    .filter((cell) => cell !== "");
  const total = perInning.reduce((sum, cell) => sum + (int(cell) ?? 0), 0);
  const trustworthy = perInning.length > 0 && runs !== null && total === runs;

  lines.push(
    `INSERT INTO historical_line_scores (game_id, is_home, team_label, innings, runs, hits, errors)` +
      ` SELECT id, ${index === 1 ? 1 : 0}, ${sqlStr(row[0])}, ${
        trustworthy ? sqlStr(perInning.join(",")) : "NULL"
      }, ${sqlNum(runs)}, ${sqlNum(int(row[hIndex]))}, ${sqlNum(int(row[eIndex]))}` +
      ` FROM historical_games WHERE source_game_id = ${sqlStr(sourceGameId)};`,
  );
  if (!trustworthy) {
    console.log(`  ${row[0]}: per-inning cells do not total ${runs} - storing R/H/E only.`);
  }
  sides += 1;
});

// The final score comes from the line score's own run totals.
const awayRuns = int(game.line[1]?.[rIndex]);
const homeRuns = int(game.line[2]?.[rIndex]);
lines.push(
  `UPDATE historical_games SET away_score = ${sqlNum(awayRuns)}, home_score = ${sqlNum(
    homeRuns,
  )} WHERE source_game_id = ${sqlStr(sourceGameId)};`,
);

let statRows = 0;
const emit = (tables, mapping, kind, nameHeader) => {
  tables.forEach((table, tableIndex) => {
    const head = table[0];
    const nameIndex = head.indexOf(nameHeader);
    if (nameIndex === -1) return;
    const isHome = tableIndex === 1 ? 1 : 0;

    for (const row of table.slice(1)) {
      const player = (row[nameIndex] ?? "").trim();
      if (!player || /^totals?$/i.test(player)) continue;

      const stats = {};
      head.forEach((cell, index) => {
        const column = mapping[cell];
        if (!column) return;
        stats[column] = column === "inningsPitched" ? innings(row[index]) : int(row[index]);
      });

      lines.push(
        `INSERT INTO historical_game_stats (game_id, is_home, kind, player_name, ${COLUMNS.map(
          snake,
        ).join(", ")}) SELECT id, ${isHome}, ${sqlStr(kind)}, ${sqlStr(player)}, ${COLUMNS.map(
          (c) => sqlNum(stats[c] ?? null),
        ).join(", ")} FROM historical_games WHERE source_game_id = ${sqlStr(sourceGameId)};`,
      );
      statRows += 1;
    }
  });
};

emit(game.batting ?? [], BAT, "BATTING", "BATTERS");
emit(game.pitching ?? [], PIT, "PITCHING", "PITCHERS");

fs.writeFileSync(outputPath, lines.join("\n") + "\n", "utf8");
console.log(
  `Wrote ${outputPath}\n  final score: ${awayRuns}-${homeRuns}\n  line score sides: ${sides}\n  player game lines: ${statRows}`,
);
