/**
 * Imports per-game line scores and box scores.
 *
 *   node scripts/import-boxscores.mjs <boxscores.json> <gameids.json> <schedule.json> [out.sql]
 *
 * Games are matched to the already-imported historical_games rows by position:
 * the game-id list and the schedule were parsed from the same page in the same
 * order, and every season's counts line up exactly. Seasons IV and V are absent
 * from the id list on purpose - their per-game data is unreliable.
 */
import fs from "node:fs";
import path from "node:path";

const [, , boxPath, idsPath, schedulePath, outPath] = process.argv;
if (!boxPath || !idsPath || !schedulePath) {
  console.error(
    "usage: node scripts/import-boxscores.mjs <boxscores.json> <gameids.json> <schedule.json> [out.sql]",
  );
  process.exit(1);
}
const outputPath = outPath ?? path.join("drizzle", "seed-boxscores.sql");

const box = JSON.parse(fs.readFileSync(boxPath, "utf8"));
const ids = JSON.parse(fs.readFileSync(idsPath, "utf8"));
const schedule = JSON.parse(fs.readFileSync(schedulePath, "utf8"));

const num = (value) => {
  if (value === undefined || value === null) return null;
  const text = String(value).trim();
  if (!text || text === "-" || text === "--") return null;
  const parsed = Number.parseFloat(text);
  return Number.isFinite(parsed) ? parsed : null;
};
const int = (value) => {
  const parsed = num(value);
  return parsed === null ? null : Math.round(parsed);
};
/** Innings pitched use baseball notation: .1 and .2 mean thirds. */
const innings = (value) => {
  const raw = num(value);
  if (raw === null) return null;
  const whole = Math.trunc(raw);
  const outs = Math.round((raw - whole) * 10);
  return outs === 1 ? whole + 1 / 3 : outs === 2 ? whole + 2 / 3 : whole;
};
const sqlStr = (value) =>
  value === null || value === undefined ? "NULL" : `'${String(value).replace(/'/g, "''")}'`;
const sqlNum = (value) => (value === null || value === undefined ? "NULL" : String(value));

/**
 * Rows reference their game through a subquery on the source id rather than a
 * reconstructed row number - generated ids depend on insertion order, which is
 * not something this seed should be guessing at.
 */
const knownSourceIds = new Set(ids.seasons.flatMap((season) => season.gameIds));

const BAT = {
  AB: "atBats", R: "runs", H: "hits", "2B": "doubles", "3B": "triples",
  HR: "homeRuns", RBI: "rbis", BB: "walks", SO: "strikeouts",
};
const PIT = {
  IP: "inningsPitched", ER: "earnedRuns", H: "hitsAllowed", R: "runsAllowed",
  SO: "strikeoutsPitched", BB: "walksAllowed",
};

const COLUMNS = [
  "atBats", "runs", "hits", "doubles", "triples", "homeRuns", "rbis", "walks",
  "strikeouts", "inningsPitched", "earnedRuns", "hitsAllowed", "runsAllowed",
  "strikeoutsPitched", "walksAllowed",
];
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);

const lines = [
  "-- Generated by scripts/import-boxscores.mjs - do not edit by hand.",
  "DELETE FROM historical_game_stats;",
  "DELETE FROM historical_line_scores;",
  "",
];

let lineRows = 0;
let statRows = 0;
let unmatched = 0;

for (const game of box.games) {
  if (!knownSourceIds.has(game.gameId)) {
    unmatched += 1;
    continue;
  }

  if (game.line && game.line.length >= 3) {
    const header = game.line[0];
    const rIndex = header.lastIndexOf("R");
    const hIndex = header.lastIndexOf("H");
    const eIndex = header.lastIndexOf("E");
    // Everything between the team name and the R column is per-inning scoring.
    const inningEnd = Math.min(...[rIndex, hIndex, eIndex].filter((i) => i > 0));

    game.line.slice(1, 3).forEach((row, index) => {
      const perInning = row
        .slice(1, inningEnd)
        .filter((cell) => cell !== "")
        .join(",");
      lines.push(
        // INSERT ... SELECT rather than VALUES: a game the importer drops as
        // never-played has no row to point at, and this simply inserts nothing
        // instead of failing the NOT NULL constraint.
        `INSERT INTO historical_line_scores (game_id, is_home, team_label, innings, runs, hits, errors) SELECT id, ${
          index === 1 ? 1 : 0
        }, ${sqlStr(row[0])}, ${sqlStr(perInning || null)}, ${sqlNum(int(row[rIndex]))}, ${sqlNum(
          int(row[hIndex]),
        )}, ${sqlNum(int(row[eIndex]))} FROM historical_games WHERE source_game_id = ${sqlStr(game.gameId)};`,
      );
      lineRows += 1;
    });
  }

  const emit = (tables, mapping, kind, nameHeader) => {
    tables.forEach((table, tableIndex) => {
      const header = table[0];
      const nameIndex = header.indexOf(nameHeader);
      if (nameIndex === -1) return;
      // The source lists away first, then home.
      const isHome = tableIndex === 1 ? 1 : 0;

      for (const row of table.slice(1)) {
        const player = (row[nameIndex] ?? "").trim();
        if (!player || /^totals?$/i.test(player)) continue;

        const stats = {};
        header.forEach((cell, index) => {
          const column = mapping[cell];
          if (!column) return;
          stats[column] =
            column === "inningsPitched" ? innings(row[index]) : int(row[index]);
        });

        lines.push(
          `INSERT INTO historical_game_stats (game_id, is_home, kind, player_name, ${COLUMNS.map(
            snake,
          ).join(", ")}) SELECT id, ${isHome}, ${sqlStr(kind)}, ${sqlStr(
            player,
          )}, ${COLUMNS.map((c) => sqlNum(stats[c] ?? null)).join(
            ", ",
          )} FROM historical_games WHERE source_game_id = ${sqlStr(game.gameId)};`,
        );
        statRows += 1;
      }
    });
  };

  emit(game.batting ?? [], BAT, "BATTING", "BATTERS");
  emit(game.pitching ?? [], PIT, "PITCHING", "PITCHERS");
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(
  `Wrote ${outputPath}\n  line score rows: ${lineRows}\n  player game lines: ${statRows}\n  unmatched games: ${unmatched}`,
);
