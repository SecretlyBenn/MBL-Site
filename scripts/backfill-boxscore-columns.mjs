/**
 * Fills in box score columns the original import never read.
 *
 *   node scripts/backfill-boxscore-columns.mjs <boxscores.json> [out.sql]
 *
 * The importer used to read nine batting columns and six pitching ones, so
 * every per-game row in the archive has nothing for putouts, errors, stolen
 * bases, sacrifice flies, wins, saves and the rest - even though the source
 * page carries all of them. Recomputing a season from those rows then replaced
 * its real totals with nothing.
 *
 * This only ever UPDATEs rows that already exist, matched on game, side of the
 * sheet and player. It inserts nothing and deletes nothing, so running it twice
 * - or against a season it has nothing for - leaves the archive as it was.
 * Counting columns the earlier import did fill are not touched.
 *
 * Takes the output of scrape-mso-boxscores.mjs.
 */
import fs from "node:fs";
import path from "node:path";

const [, , boxPath, outPath] = process.argv;
if (!boxPath) {
  console.error("usage: node scripts/backfill-boxscore-columns.mjs <boxscores.json> [out.sql]");
  process.exit(1);
}
const outputPath = outPath ?? path.join("drizzle", "backfill-boxscore-columns.sql");

/** Source header -> column, for the columns the first import skipped. */
const BAT = {
  PO: "putouts", E: "errors", SB: "stolenBases", CS: "caughtStealing",
  SF: "sacFlies", LOB: "leftOnBase",
};
const PIT = {
  HR: "homeRunsAllowed", W: "wins", L: "losses", SV: "saves",
  BS: "blownSaves", CG: "completeGames", SHO: "shutouts", GS: "gamesStarted",
};

const int = (value) => {
  const text = String(value ?? "").trim();
  if (!text || text === "-" || text === "--") return null;
  const parsed = Number.parseFloat(text);
  return Number.isFinite(parsed) ? Math.round(parsed) : null;
};
const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const sqlStr = (value) => `'${String(value).replace(/'/g, "''")}'`;

const box = JSON.parse(fs.readFileSync(boxPath, "utf8"));
const lines = [
  "-- Generated by scripts/backfill-boxscore-columns.mjs.",
  "-- UPDATE only: fills columns on existing per-game rows, inserts and deletes nothing.",
];
let updates = 0;

for (const game of box.games ?? []) {
  const emit = (tables, mapping, kind, nameHeader) => {
    tables.forEach((table, tableIndex) => {
      const header = table[0] ?? [];
      const nameIndex = header.indexOf(nameHeader);
      if (nameIndex === -1) return;
      // The source lists the away side first, then home.
      const isHome = tableIndex === 1 ? 1 : 0;

      for (const row of table.slice(1)) {
        const player = (row[nameIndex] ?? "").trim();
        if (!player || /^totals?$/i.test(player)) continue;

        const sets = [];
        header.forEach((cell, index) => {
          const column = mapping[cell];
          if (!column) return;
          const value = int(row[index]);
          // Leave a column alone rather than writing NULL over it when the
          // source cell is blank.
          if (value !== null) sets.push(`${snake(column)} = ${value}`);
        });
        if (sets.length === 0) continue;

        lines.push(
          `UPDATE historical_game_stats SET ${sets.join(", ")} WHERE kind = ${sqlStr(kind)}` +
            ` AND is_home = ${isHome} AND player_name = ${sqlStr(player)}` +
            ` AND game_id = (SELECT id FROM historical_games WHERE source_game_id = ${sqlStr(game.gameId)});`,
        );
        updates += 1;
      }
    });
  };

  emit(game.batting ?? [], BAT, "BATTING", "BATTERS");
  emit(game.pitching ?? [], PIT, "PITCHING", "PITCHERS");
}

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${outputPath}\n  games: ${(box.games ?? []).length}\n  row updates: ${updates}`);
